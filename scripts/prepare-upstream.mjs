import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { git, json, pin, prepared, root, verifyPin } from './upstream-lib.mjs';

function writeJson(file, value) { writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`); }

try {
  if (process.argv.slice(2).some(arg => arg !== '--reset')) throw new Error('Usage: node scripts/prepare-upstream.mjs [--reset]');
  verifyPin();
  const marker = resolve(prepared, '.minv-prepared.json');
  if (existsSync(prepared)) {
    if (!process.argv.includes('--reset') || !existsSync(marker) || json(marker).owner !== 'minv-prepare') {
      throw new Error('Destination exists. --reset replaces only a directory previously generated by this script.');
    }
    rmSync(prepared, { recursive: true });
  }
  mkdirSync(prepared, { recursive: true });
  writeJson(marker, { owner: 'minv-prepare', commit: pin.commit, complete: false });
  const archive = resolve(root, '.upstream/minv-source.tar');
  try {
    git(['archive', '--format=tar', '-o', archive, pin.commit]);
    execFileSync('tar', ['-xf', archive, '-C', prepared]);
  } finally { rmSync(archive, { force: true }); }

  copyFileSync(resolve(root, 'product/product.json'), resolve(prepared, 'product.json'));
  const policy = json(resolve(root, 'product/contributions.json'));
  const removedImports = {};
  for (const [file, rule] of Object.entries(policy.entrypoints)) {
    const source = readFileSync(resolve(prepared, file), 'utf8');
    if (createHash('sha256').update(source).digest('hex') !== rule.sha256) throw new Error(`Unreviewed entrypoint: ${file}`);
    const imports = [...source.matchAll(/^import '([^']+)';$/gm)].map(match => match[1]);
    if (imports.some(spec => !rule.keepImports.includes(spec) && !rule.removedImports.includes(spec))) throw new Error(`Unclassified import in ${file}`);
    removedImports[file] = rule.removedImports;
    writeFileSync(resolve(prepared, file), source.replace(/^import '([^']+)';\n/gm, (line, spec) => rule.keepImports.includes(spec) ? line : ''));
  }

  for (const patch of readdirSync(resolve(root, 'patches')).filter(name => name.endsWith('.patch')).sort()) {
    git(['apply', '--check', resolve(root, 'patches', patch)], prepared);
    git(['apply', resolve(root, 'patches', patch)], prepared);
  }

  const extensions = json(resolve(root, 'product/extensions.json'));
  const removedExtensions = [];
  for (const entry of readdirSync(resolve(prepared, 'extensions'), { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const folder = resolve(prepared, 'extensions', entry.name);
    if (!extensions.allow.includes(entry.name)) {
      removedExtensions.push(entry.name);
      rmSync(folder, { recursive: true });
      continue;
    }
    const manifestFile = resolve(folder, 'package.json');
    const manifest = json(manifestFile);
    for (const key of ['main', 'browser', 'activationEvents', 'extensionDependencies', 'extensionPack', 'scripts', 'dependencies', 'devDependencies', 'enabledApiProposals']) delete manifest[key];
    manifest.contributes = Object.fromEntries(Object.entries(manifest.contributes ?? {}).filter(([key]) => extensions.allowedContributionKeys.includes(key)));
    writeJson(manifestFile, manifest);
    // Retain only declarative assets and their legal notices, not dormant source code.
    for (const dir of ['src', 'out', 'dist', 'build', 'scripts', 'node_modules']) rmSync(resolve(folder, dir), { recursive: true, force: true });
  }

  const pkgFile = resolve(prepared, 'package.json');
  const pkg = json(pkgFile);
  pkg.name = 'minv-source';
  pkg.scripts.compile = 'npm run compile-client';
  pkg.scripts.watch = 'npm-run-all2 -lp watch-client-transpile watch-client watch-extensions';
  pkg.scripts['watch-transpile'] = 'npm-run-all2 -lp watch-client-transpile watch-extensions';
  for (const name of Object.keys(pkg.scripts)) if (/copilot|agent-host|codex/.test(name)) delete pkg.scripts[name];
  writeJson(pkgFile, pkg);
  const lockFile = resolve(prepared, 'package-lock.json');
  const lock = json(lockFile);
  lock.name = pkg.name;
  if (lock.packages?.['']) lock.packages[''].name = pkg.name;
  writeJson(lockFile, lock);

  writeJson(marker, { owner: 'minv-prepare', commit: pin.commit, complete: true, releaseReady: false, removedImports, removedExtensions, releaseBlockers: policy.releaseBlockers });
  console.log(`Prepared ${prepared}\nRun node scripts/upstream-audit.mjs to inspect remaining excluded dependencies.\nThis is source-removal preparation, not a runnable or releasable desktop build.`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
